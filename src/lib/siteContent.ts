export type ContentPageKey = keyof typeof DEFAULT_CONTENT;
export type SiteContent = {
  [P in ContentPageKey]: { [F in keyof (typeof DEFAULT_CONTENT)[P]]: string };
};

export function isContentPageKey(value: unknown): value is ContentPageKey {
  return typeof value === "string" && value in DEFAULT_CONTENT;
}

/** Merge stored (partial) values over defaults; blank values use the default. */
export function mergeContent(
  stored: Partial<Record<string, Record<string, unknown>>>
): SiteContent {
  const result = {} as Record<string, Record<string, string>>;
  for (const page of Object.keys(DEFAULT_CONTENT) as ContentPageKey[]) {
    const defaults = DEFAULT_CONTENT[page] as Record<string, string>;
    const saved = stored[page] ?? {};
    result[page] = {};
    for (const field of Object.keys(defaults)) {
      const value = saved[field];
      result[page][field] =
        typeof value === "string" && value.trim() ? value : defaults[field];
    }
  }
  return result as SiteContent;
}


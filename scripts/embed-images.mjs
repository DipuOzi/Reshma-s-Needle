#!/usr/bin/env node
// Copies every picture in public/images into plain-text TypeScript files
// (src/lib/embeddedImages). Zip files, git and some download tools drop binary
// files; text files always survive. If a picture is missing from public/images
// the website serves the embedded copy from /images/<name> automatically.
//
//   node scripts/embed-images.mjs
//
// Run it again after you add or replace pictures in public/images.
// (A picture that exists in public/images always wins over the embedded copy.)

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imageDir = path.join(root, "public", "images");
const outDir = path.join(root, "src", "lib", "embeddedImages");
const dataDir = path.join(outDir, "data");

const TYPES = {
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".webp": "image/webp",
  ".gif": "image/gif",
  ".avif": "image/avif",
};

rmSync(dataDir, { recursive: true, force: true });
mkdirSync(dataDir, { recursive: true });

const entries = [];
let totalBytes = 0;

for (const file of readdirSync(imageDir).sort()) {
  const type = TYPES[path.extname(file).toLowerCase()];
  if (!type) continue;

  const bytes = readFileSync(path.join(imageDir, file));
  const id = file.replace(/[^a-zA-Z0-9]+/g, "_");
  totalBytes += bytes.length;

  writeFileSync(
    path.join(dataDir, `${id}.ts`),
    `// Generated by scripts/embed-images.mjs from public/images/${file}. Do not edit.\n` +
      `const data = "${bytes.toString("base64")}";\nexport default data;\n`
  );
  entries.push({ file, id, type });
}

const lines = entries.map(
  ({ file, id, type }) =>
    `  ${JSON.stringify(file)}: { type: ${JSON.stringify(type)}, load: () => import("./data/${id}") },`
);

writeFileSync(
  path.join(outDir, "index.ts"),
  `// Generated by scripts/embed-images.mjs. Do not edit by hand.\n` +
    `export interface EmbeddedImage {\n` +
    `  type: string;\n` +
    `  load: () => Promise<{ default: string }>;\n` +
    `}\n\n` +
    `export const EMBEDDED_IMAGES: Record<string, EmbeddedImage> = {\n${lines.join("\n")}\n};\n`
);

console.log(
  `Embedded ${entries.length} image(s), ${(totalBytes / 1024).toFixed(0)} KB, into src/lib/embeddedImages`
);
